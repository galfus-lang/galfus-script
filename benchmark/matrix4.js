const ITERATIONS = 1_000_000;
const MODULUS = 1_000_000_007n;

function matrix4() {
  let a00 = 1_000_000_000n,
    a01 = 1_000_000_001n,
    a02 = 1_000_000_002n,
    a03 = 1_000_000_003n;
  let a10 = 1_000_000_004n,
    a11 = 1_000_000_005n,
    a12 = 1_000_000_006n,
    a13 = 1_000_000_007n;
  let a20 = 1_000_000_008n,
    a21 = 1_000_000_009n,
    a22 = 1_000_000_010n,
    a23 = 1_000_000_011n;
  let a30 = 1_000_000_012n,
    a31 = 1_000_000_013n,
    a32 = 1_000_000_014n,
    a33 = 1_000_000_015n;
  const b00 = 1_000_000_001n,
    b01 = 1_000_000_002n,
    b02 = 1_000_000_003n,
    b03 = 1_000_000_004n;
  const b10 = 1_000_000_002n,
    b11 = 1_000_000_001n,
    b12 = 1_000_000_004n,
    b13 = 1_000_000_003n;
  const b20 = 1_000_000_003n,
    b21 = 1_000_000_004n,
    b22 = 1_000_000_001n,
    b23 = 1_000_000_002n;
  const b30 = 1_000_000_004n,
    b31 = 1_000_000_003n,
    b32 = 1_000_000_002n,
    b33 = 1_000_000_001n;
  let checksum = 0n;
  for (let index = 0; index < ITERATIONS; index += 1) {
    const c00 = (a00 * b00 + a01 * b10 + a02 * b20 + a03 * b30) % MODULUS,
      c01 = (a00 * b01 + a01 * b11 + a02 * b21 + a03 * b31) % MODULUS,
      c02 = (a00 * b02 + a01 * b12 + a02 * b22 + a03 * b32) % MODULUS,
      c03 = (a00 * b03 + a01 * b13 + a02 * b23 + a03 * b33) % MODULUS;
    const c10 = (a10 * b00 + a11 * b10 + a12 * b20 + a13 * b30) % MODULUS,
      c11 = (a10 * b01 + a11 * b11 + a12 * b21 + a13 * b31) % MODULUS,
      c12 = (a10 * b02 + a11 * b12 + a12 * b22 + a13 * b32) % MODULUS,
      c13 = (a10 * b03 + a11 * b13 + a12 * b23 + a13 * b33) % MODULUS;
    const c20 = (a20 * b00 + a21 * b10 + a22 * b20 + a23 * b30) % MODULUS,
      c21 = (a20 * b01 + a21 * b11 + a22 * b21 + a23 * b31) % MODULUS,
      c22 = (a20 * b02 + a21 * b12 + a22 * b22 + a23 * b32) % MODULUS,
      c23 = (a20 * b03 + a21 * b13 + a22 * b23 + a23 * b33) % MODULUS;
    const c30 = (a30 * b00 + a31 * b10 + a32 * b20 + a33 * b30) % MODULUS,
      c31 = (a30 * b01 + a31 * b11 + a32 * b21 + a33 * b31) % MODULUS,
      c32 = (a30 * b02 + a31 * b12 + a32 * b22 + a33 * b32) % MODULUS,
      c33 = (a30 * b03 + a31 * b13 + a32 * b23 + a33 * b33) % MODULUS;
    a00 = c00;
    a01 = c01;
    a02 = c02;
    a03 = c03;
    a10 = c10;
    a11 = c11;
    a12 = c12;
    a13 = c13;
    a20 = c20;
    a21 = c21;
    a22 = c22;
    a23 = c23;
    a30 = c30;
    a31 = c31;
    a32 = c32;
    a33 = c33;
    checksum += a00 + a11 + a22 + a33;
  }
  return checksum;
}

const start = performance.now();
const result = matrix4();
console.log(`RESULT=${result}`);
console.log(`TIME_MS=${Math.round(performance.now() - start)}`);
